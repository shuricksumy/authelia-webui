router = APIRouter()
NO_STORE = {"Cache-Control": "no-store, max-age=0", "Pragma": "no-cache"}


# --------------------------------------------------------------------------- helpers


def clients_of(v: View) -> ClientsDocument | None:
    return ClientsDocument.parse(v.clients_text) if v.clients_text else None


def names_of(v: View) -> OidcNames:
    return load_oidc_names(v.settings.CONFIG_MAIN)


def commit_clients(v: View, doc: ClientsDocument) -> None:
    """Compare-and-swap save of the clients into the draft (rules and disabled unchanged)."""
    try:
        v.store.save(v.doc, expected_sha=v.sha, clients=doc)
    except StaleDraftError:
        raise Conflict(STALE) from None


def require_clients(v: View) -> ClientsDocument:
    doc = clients_of(v)
    if doc is None:
        raise Conflict("This deployment has no OIDC clients file.", 404)
    return doc


def check_index(doc: ClientsDocument, index: int) -> None:
    if not 0 <= index < len(doc.blocks):
        raise Conflict("That client no longer exists. Reload the page.", 404)


def generate_secret(v: View) -> tuple[str, str]:
    try:
        return AutheliaCLI.local(v.settings.AUTHELIA_BINARY).hash_random_pbkdf2()
    except AutheliaCLIError:
        raise Conflict(
            "Authelia could not generate a secret here; nothing was changed.", 503
        ) from None


def audit_secret(v: View, client_id: str) -> None:
    audit.append(
        v.settings.CONFIG_MANAGED_DIR,
        audit.AuditEntry(
            ts=audit.now(), user=v.identity.username, client_ip=str(v.identity.client_ip),
            action="client-secret", result="draft", commit="",
            summary=f"New secret generated for client {client_id[:80]} (in the draft).",
        ),
    )  # fmt: skip


def setup_info(v: View, client: dict[str, Any]) -> dict[str, Any]:
    issuer = f"https://{v.settings.AUTH_DOMAIN}"
    return {
        "issuer": issuer,
        "discovery": f"{issuer}/.well-known/openid-configuration",
        "client_id": str(client.get("client_id", "")),
        "redirect_uris": [str(u) for u in client.get("redirect_uris") or []],
        "auth_method": auth_method(client),
        "public": is_public(client),
    }


def secret_response(v: View, secret: str, client: dict[str, Any], created: bool) -> HTMLResponse:
    """The one-time modal. Swapped into #modal whatever the triggering element targeted."""
    response = render(
        v, "partials/secret_modal.html", secret=secret, created=created,
        info=setup_info(v, client),
    )  # fmt: skip
    response.headers.update(NO_STORE)
    response.headers["HX-Retarget"] = "#modal"
    response.headers["HX-Reswap"] = "innerHTML"
    response.headers["HX-Reselect"] = "dialog"  # the editor form selects #editor otherwise
    return response


# --------------------------------------------------------------------------- list


def hosts(uris: Any) -> list[str]:
    out: list[str] = []
    for uri in uris or []:
        host = urlsplit(str(uri)).hostname or str(uri).split(":", 1)[0] + ":"
        if host not in out:
            out.append(host)
    return out


@router.get("/clients", response_class=HTMLResponse)
def clients_page(request: Request, saved: str = "") -> Response:
    v = load_view(request)
    doc = clients_of(v)
    rows: list[dict[str, Any]] = []
    issues: list[Issue] = []
    if doc is not None:
        clients = doc.clients()
        issues = lint_clients(clients, names_of(v))
        live = v.store.live_clients()
        live_blocks = {b.lines for b in live.blocks} if live else set()
        for i, client in enumerate(clients):
            rows.append({
                "index": i,
                "name": str(client.get("client_name") or ""),
                "client_id": str(client.get("client_id") or ""),
                "hosts": hosts(client.get("redirect_uris")),
                "policy": str(client.get("authorization_policy") or "two_factor"),
                "pkce": client.get("require_pkce") is True,
                "public": is_public(client),
                "secret": secret_kind(client.get("client_secret")),
                "issues": [x for x in issues if x.rule == i],
                "changed": doc.blocks[i].lines not in live_blocks,
            })  # fmt: skip
    return render(
        v, "oidc_clients.html", active="clients", rows=rows, has_clients_file=doc is not None,
        doc_issues=[x for x in issues if x.rule is None], labels=POLICY_LABEL,
        flash=f"Client {saved} saved to the draft." if saved else "",
    )  # fmt: skip


# --------------------------------------------------------------------------- editor


def editor_context(
    v: View, index: int | None, form: F.ClientForm, errors: list[str] | None = None,
    inner_comments: bool = False, secret: str = "",
) -> dict[str, Any]:  # fmt: skip
    names = names_of(v)
    return {
        "active": "clients", "index": index, "form": form, "errors": errors or [],
        "names": names, "UNSET": F.UNSET, "inner_comments": inner_comments, "secret_kind": secret,
        "grant_types": F.GRANT_TYPES, "response_types": F.RESPONSE_TYPES,
        "response_modes": F.RESPONSE_MODES, "auth_methods": F.AUTH_METHODS,
        "pkce_methods": F.PKCE_METHODS, "consent_modes": F.CONSENT_MODES,
        "signing_algs": F.SIGNING_ALGS, "signed_keys": F.SIGNED_RESPONSE_KEYS,
        "redirect_text": "\n".join(form.lists.get("redirect_uris") or []),
    }  # fmt: skip


@router.get("/clients/new", response_class=HTMLResponse)
def new_client(request: Request, template: str = "", host: str = "") -> Response:
    """Step 1: pick a preset (cards). Step 2: the editor, filled from the preset."""
    v = load_view(request)
    if not v.clients_text:
        return conflict_response(Conflict("This deployment has no OIDC clients file.", 404))
    names = names_of(v)
    if not template:
        cards = [{"t": t, "missing": missing_names(t, names)} for t in templates.load_all()]
        return render(v, "client_picker.html", active="clients", cards=cards, error="")
    chosen = templates.get(template)
    if chosen is None:
        return conflict_response(Conflict("Unknown preset.", 404))
    typed = host.strip()
    clean = templates.clean_host(typed) if typed else ""
    if typed and clean is None:
        cards = [{"t": t, "missing": missing_names(t, names)} for t in templates.load_all()]
        problem = f"'{typed[:60]}' is not a valid address (host or host:port)."
        return render(v, "client_picker.html", status=422, active="clients", cards=cards,
                      error=problem)  # fmt: skip
    form = F.ClientForm.from_data(chosen.instantiate(clean or ""))
    ids = ClientsDocument.parse(v.clients_text).client_ids()
    if form.client_id in ids:  # a second client of the same app: pick a free id
        n = 2
        while f"{chosen.id}-{n}" in ids:
            n += 1
        form.client_id = f"{chosen.id}-{n}"
    ctx = editor_context(v, None, form)
    ctx.update(preset=chosen, preset_missing=missing_names(chosen, names), host_given=bool(clean))
    return render(v, "client_editor.html", **ctx)


def missing_names(template: templates.Template, names: OidcNames) -> list[str]:
    """Names a preset's client uses that the main config does not define yet."""
    c = template.client
    out = []
    if c.get("claims_policy") and str(c["claims_policy"]) not in names.claims_policies:
        out.append(f"claims policy '{c['claims_policy']}'")
    for scope in c.get("scopes", []):
        if scope not in names.scopes:
            out.append(f"scope '{scope}'")
    return out


@router.get("/clients/{index}/edit", response_class=HTMLResponse)
def edit_client(request: Request, index: int) -> Response:
    v = load_view(request)
    try:
        doc = require_clients(v)
        check_index(doc, index)
    except Conflict as exc:
        return conflict_response(exc)
    block = doc.blocks[index]
    data = block.data()
    form = F.ClientForm.from_data(data)
    ctx = editor_context(
        v, index, form, inner_comments=block.has_inner_comments,
        secret=secret_kind(data.get("client_secret")),
    )  # fmt: skip
    ctx["info"] = setup_info(v, data)
    return render(v, "client_editor.html", **ctx)


def form_from_request(data: Any) -> F.ClientForm:
    """Field names: s_<key> scalars, b_<key> tri-state bools, l_<key> lists (checkbox groups or
    one-per-line textareas), present_<key> marks a list that exists (possibly empty)."""

    def text(name: str) -> str:
        return str(data.get(name, "")).replace("\r\n", "\n")

    lists: dict[str, list[str] | None] = {}
    for key in F.LISTS:
        values = [str(x) for x in data.getlist(f"l_{key}")]
        if key == "redirect_uris":
            values = [line for line in text("l_redirect_uris").split("\n")]
        values = [x.strip() for x in values if x.strip()]
        lists[key] = values if values or data.get(f"present_{key}") else None
    scalars = {}
    for key in F.SCALARS:
        raw = text(f"s_{key}")
        if raw == F.UNSET or (raw == "" and not data.get(f"empty_{key}")):
            scalars[key] = F.UNSET
        else:
            scalars[key] = raw
    bools = {
        k: (text(f"b_{k}") if text(f"b_{k}") in ("true", "false") else F.UNSET) for k in F.BOOLS
    }
    return F.ClientForm(
        client_id=text("client_id").strip(), scalars=scalars, lists=lists, bools=bools,
        extra_yaml=text("extra_yaml").strip("\n"),
    )  # fmt: skip


@router.post("/clients/save", response_class=HTMLResponse)
async def save_client(request: Request) -> Response:
    data = await request.form()  # before load_view: no await between reading and saving
    v = load_view(request)
    raw_index = str(data.get("index", "")).strip()
    index = int(raw_index) if raw_index.isdigit() else None
    form = form_from_request(data)
    try:
        require_rev(v, str(data.get("rev", "")))
        doc = require_clients(v)
        if index is not None:
            check_index(doc, index)
    except Conflict as exc:
        return conflict_response(exc)

    errors: list[str] = []
    new_doc = doc
    try:
        F.check(form)
        if index is None:
            node = F.apply_client_form(form)
            new_doc = doc.insert(len(doc.blocks), node)
            position = len(doc.blocks)
        else:
            node = F.apply_client_form(form, doc.blocks[index].node())
            new_doc = doc.replace_item(index, node)
            position = index
    except (F.FormError, F.DocumentError) as exc:
        errors.append(str(exc))
        position = index if index is not None else len(doc.blocks)

    needs_secret = False
    if not errors:
        client = new_doc.clients()[position]
        needs_secret = (
            not is_public(client)
            and not secret_kind(client.get("client_secret"))
            and (auth_method(client) in ("client_secret_basic", "client_secret_post"))
        )
        issues = lint_clients(new_doc.clients(), names_of(v))
        mine = [i for i in blocking(issues) if i.rule == position]
        if needs_secret:  # will be generated below; do not block on it
            mine = [i for i in mine if i.code != "confidential-without-secret"]
        errors += [i.message for i in mine]
    if errors:
        return render(v, "client_editor.html", status=422, **editor_context(v, index, form, errors))

    secret = ""
    if needs_secret:
        try:
            secret, digest = await run_in_threadpool(generate_secret, v)
        except Conflict as exc:
            return render(v, "client_editor.html", status=422,
                          **editor_context(v, index, form, [exc.message]))  # fmt: skip
        new_doc = new_doc.with_secret(position, digest)
    try:
        commit_clients(v, new_doc)
    except Conflict as exc:
        return conflict_response(exc)
    client = new_doc.clients()[position]
    if secret:
        audit_secret(v, str(client.get("client_id", "")))
        return secret_response(v, secret, client, created=index is None)
    return Response(status_code=204,
                    headers={"HX-Redirect": f"/clients?saved={position + 1}"})  # fmt: skip


@router.post("/clients/{index}/secret", response_class=HTMLResponse)
async def rotate_secret(request: Request, index: int) -> Response:
    data = await request.form()
    v = load_view(request)
    try:
        require_rev(v, str(data.get("rev", "")))
        doc = require_clients(v)
        check_index(doc, index)
        client = doc.clients()[index]
        if is_public(client):
            raise Conflict("A public client has no secret.", 422)
        if auth_method(client) not in ("client_secret_basic", "client_secret_post"):
            # client_secret_jwt needs the plaintext in Authelia; private_key_jwt uses keys
            raise Conflict(f"Clients using {auth_method(client)} cannot get a hashed secret here; "
                           "edit them by hand.", 422)  # fmt: skip
        secret, digest = await run_in_threadpool(generate_secret, v)
        new_doc = doc.with_secret(index, digest)
        commit_clients(v, new_doc)
    except Conflict as exc:
        return conflict_response(exc)
    audit_secret(v, str(client.get("client_id", "")))
    return secret_response(v, secret, new_doc.clients()[index], created=False)


@router.post("/clients/generate-id", response_class=HTMLResponse)
async def generate_id(request: Request) -> Response:
    v = load_view(request)
    try:
        value = await run_in_threadpool(
            lambda: AutheliaCLI.local(v.settings.AUTHELIA_BINARY).rand_client_id()
        )
    except AutheliaCLIError:
        return conflict_response(Conflict("Authelia could not generate an id here.", 503))
    return render(v, "partials/client_id_input.html", value=value)


