@router.get("/clients/{index}/delete", response_class=HTMLResponse)
def delete_confirm(request: Request, index: int) -> Response:
    v = load_view(request)
    try:
        doc = require_clients(v)
        check_index(doc, index)
    except Conflict as exc:
        return conflict_response(exc)
    client = doc.clients()[index]
    return render(v, "partials/client_delete_confirm.html", index=index,
                  client_id=str(client.get("client_id", "")),
                  client_name=str(client.get("client_name") or ""))  # fmt: skip


@router.post("/clients/{index}/delete", response_class=HTMLResponse)
async def delete_client(request: Request, index: int) -> Response:
    data = await request.form()
    v = load_view(request)
    try:
        require_rev(v, str(data.get("rev", "")))
        doc = require_clients(v)
        check_index(doc, index)
        commit_clients(v, doc.delete(index))
    except Conflict as exc:
        return conflict_response(exc)
    return Response(status_code=204, headers={"HX-Redirect": "/clients"})
