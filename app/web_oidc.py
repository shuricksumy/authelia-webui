"""OIDC clients pages (SPEC §5, §15.7). Everything edits the shared draft; apply is the usual one.

Secrets: a client secret is generated by the bundled Authelia (`--random`), shown exactly once
in the response of the request that created it (`Cache-Control: no-store`), and only its hash
goes into the draft. No page, form, log or file ever holds the plaintext; no page holds the hash.
"""

