"""OIDC signing-key rotation through the same safe apply flow as every other change.

Three steps, each its own apply (validate -> write -> commit -> restart -> health -> verify ->
rollback), because the safe order of a rotation is spread over time:

1. prepare: a new key is generated by the bundled Authelia and added *second*: apps see it in the
   key set and cache it, but Authelia still signs with the first key;
2. promote: after apps have refreshed their key set, the new key moves first and signs;
3. retire: once tokens signed by the old key have expired, the old key is removed and, only then,
   its private key file is deleted (a rollback must never point at a missing file).

After every restart the live /jwks.json must list exactly the expected key ids, else the step is
rolled back. Private keys are files in `secrets/jwks/` (mode 600, never in git); this module and
everything above it only ever handles their paths.
"""

from __future__ import annotations

import logging
import os
import secrets
import shutil
import time
from dataclasses import dataclass
from datetime import UTC, datetime
from pathlib import Path

from app.apply import probe
from app.apply import state as apply_state
from app.apply.engine import RECOVERY_HINT, TRACKED, ApplyEngine, ApplyRequest, Refused
from app.apply.jobs import Job
from app.apply.repo import RepoError
from app.apply.runtime import RuntimeUnavailable
from app.authelia_cli import AutheliaCLI, AutheliaCLIError
from app.blocklist import DocumentError
from app.oidc.jwks import JWKS_NAME, JwksDocument, KeyInfo, key_path, main_config_has_jwks
from app.rules.store import sha256

log = logging.getLogger("app.keys")
ACTIONS = ("prepare", "promote", "retire")
SUGGESTED_WAIT_S = 24 * 3600


@dataclass(frozen=True)
class KeyOp:
    action: str  # prepare | promote | retire
    kid: str  # the key to promote or retire; "" for prepare
    rev: str  # revision of the keys file the user saw
    user: str
    client_ip: str


@dataclass(frozen=True)
class KeysState:
    migrated: bool  # managed/oidc_jwks.yml exists
    doc: JwksDocument | None
    rev: str
    problem: str  # why the keys cannot be managed here ("" when they can)
    main_still_has_keys: bool
    filters_ok: bool
    prepared_at: int | None  # when the second key was added (a hint for when to promote)

    @property
    def manageable(self) -> bool:
        return self.doc is not None and not self.problem

    def can_prepare(self) -> bool:
        return self.manageable and self.doc is not None and len(self.doc.blocks) == 1

    def second_keys(self) -> list[KeyInfo]:
        """Keys that are published but not signing: they can be promoted or retired."""
        return self.doc.entries()[1:] if self.manageable and self.doc else []


def keys_state(engine: ApplyEngine) -> KeysState:
    s = engine.settings
    path = engine.managed / JWKS_NAME
    filters_ok = "template" in [f.strip() for f in s.CONFIG_FILTERS.split(",")]
    still = main_config_has_jwks(s.CONFIG_MAIN)
    prepared = apply_state.load(engine.managed).get("jwks_prepared_at")
    when = int(prepared) if isinstance(prepared, int) else None
    try:
        text = path.read_text()
    except FileNotFoundError:
        return KeysState(False, None, "", "", still, filters_ok, when)
    except OSError:
        return KeysState(True, None, "", "The keys file cannot be read.", still, filters_ok, when)
    rev = sha256(text)[:16]
    try:
        doc = JwksDocument.parse(text)
    except DocumentError as exc:
        return KeysState(True, None, rev, f"{exc}.", still, filters_ok, when)
    problem = ""
    if any(k.inline for k in doc.entries()):
        problem = "A key is still written into the file itself: move its private key out first."
    elif not filters_ok:
        problem = "Set CONFIG_FILTERS=template for the configurator, like Authelia's filter."
    return KeysState(True, doc, rev, problem, still, filters_ok, when)


def preconditions(engine: ApplyEngine, op: KeyOp) -> list[str]:
    """Plain-language reasons why this step cannot run now (empty: it can)."""
    reasons: list[str] = []
    if engine.board.running():
        reasons.append("Another apply is running.")
    elif engine._marker().exists():
        reasons.append("An earlier apply did not finish cleanly. Restart the configurator first.")
    if op.action not in ACTIONS:
        return [*reasons, "Unknown key action."]
    state = keys_state(engine)
    if not state.migrated or state.doc is None:
        return [*reasons, state.problem or "The signing keys are not set up for rotation yet."]
    if state.problem:
        reasons.append(state.problem)
        return reasons
    if op.rev != state.rev:
        reasons.append("The keys changed since you opened the page. Reload it.")
    second = [k.kid for k in state.second_keys()]
    if op.action == "prepare" and not state.can_prepare():
        reasons.append("A second key already exists: promote or retire it first.")
    if op.action in ("promote", "retire") and op.kid not in second:
        reasons.append("That key is not available for this step (the first key signs).")
    problem = engine.version_problem()
    if problem:
        reasons.append(problem)
    return reasons


def run(engine: ApplyEngine, op: KeyOp, job: Job) -> Job:
    """Run one rotation step for `job`; always returns with job.result set."""
    request = ApplyRequest(op.user, op.client_ip, op.rev)
    try:
        with engine._exclusive():
            _run(engine, op, job, request)
    except Refused as exc:
        engine._finish(job, request, "refused", str(exc), "keys")
    except (AutheliaCLIError, OSError, DocumentError) as exc:
        log.warning("key step failed: %s", type(exc).__name__)
        engine._finish(
            job, request, "failed", f"The key step failed ({type(exc).__name__}).", "keys"
        )
    except Exception:
        log.exception("key step failed unexpectedly")  # messages only; never key material
        engine._finish(job, request, "failed", "Unexpected error. " + RECOVERY_HINT, "keys")
    return job


def _run(engine: ApplyEngine, op: KeyOp, job: Job, request: ApplyRequest) -> None:
    board, managed, settings = engine.board, engine.managed, engine.settings
    if engine.repo.ensure(TRACKED) or "main_sha" not in apply_state.load(managed):
        apply_state.update(managed, main_sha=engine.main_config_sha())
    engine.repo.exclude("secrets/")  # private keys never enter git, not even by mistake
    engine._commit_external_unlocked()
    reasons = [r for r in preconditions(engine, op) if r != "Another apply is running."]
    if reasons:
        raise Refused(" ".join(reasons))
    state = keys_state(engine)
    doc = state.doc
    if doc is None:  # preconditions already refused this; belt and braces for the type
        raise Refused(state.problem or "The keys file cannot be used.")

    board.update(job, "validate", "running")
    new_pem: Path | None = None
    retired: KeyInfo | None = None
    if op.action == "prepare":
        algorithm = doc.entries()[0].algorithm
        kid = f"key-{datetime.now(UTC):%Y%m%d}-{secrets.token_hex(2)}"
        new_pem = _generate(engine, kid, algorithm)
        new_doc = doc.with_added(kid, algorithm, new_pem)
        subject = f"OIDC keys: prepared new key {kid} (published, not yet signing)"
    elif op.action == "promote":
        new_doc = doc.promoted(op.kid)
        subject = f"OIDC keys: {op.kid} now signs"
    else:
        retired = doc.get(op.kid)
        new_doc = doc.removed(op.kid)
        subject = f"OIDC keys: retired key {op.kid}"
    text = new_doc.render()
    result = engine.keys_validator(settings, text)
    if result is None or not result.ok:
        _drop(new_pem)
        reason = (
            "Authelia's validator could not run, so nothing was changed."
            if result is None
            else "Authelia rejected the new key set; nothing was changed."
        )
        board.update(job, "validate", "failed", reason,
                     details=[*(result.errors if result else [])][:10])  # fmt: skip
        raise Refused(reason)
    board.update(job, "validate", "done", "OK")

    board.update(job, "save", "running")
    try:
        before = engine.runtime.inspect(timeout_s=5).started_at
    except RuntimeUnavailable as exc:
        _drop(new_pem)
        raise Refused(f"Cannot reach Authelia's container: {exc}.") from None
    old_head = engine.repo.head()
    engine._write_marker({"old_head": old_head, "started_at": before, "user": op.user})
    engine._atomic_write(managed / JWKS_NAME, text)
    try:
        commit = engine.repo.commit([JWKS_NAME], subject, f"Applied-by: {op.user}", author=op.user)
    except RepoError:
        engine.repo.restore(JWKS_NAME)
        engine._marker().unlink(missing_ok=True)
        _drop(new_pem)
        raise Refused("Saving to git failed; the keys file was restored.") from None
    board.update(job, "save", "done", f"commit {commit[:7]}", commit=commit)

    expected = new_doc.kids()
    board.update(job, "restart", "running")
    try:
        engine.runtime.restart()
    except RuntimeUnavailable as exc:
        if not engine._restarted_since(before):
            engine.repo.revert_head(f"could not restart Authelia ({exc})", author=op.user)
            engine._marker().unlink(missing_ok=True)
            board.update(job, "restart", "failed", str(exc))
            _drop(new_pem)
            engine._finish(job, request, "rolled-back",
                           f"Authelia could not be restarted ({exc}); the change was undone.",
                           "keys", commit)  # fmt: skip
            return
        board.update(job, "restart", "done", f"restarted (the call reported: {exc})")
    else:
        board.update(job, "restart", "done")
    engine._health_or_rollback(job, request, None, before, commit,
                               verify=lambda: _verify(engine, job, expected))  # fmt: skip

    # The step's outcome is final here: tidying up must not turn "applied" into "failed".
    try:
        if job.result == "applied":
            if op.action == "prepare":
                apply_state.update(managed, jwks_prepared_at=int(time.time()))
            if retired is not None:
                _drop(_own_file(engine, retired))  # only now: a rollback needed it until here
        elif job.result == "rolled-back":
            _drop(new_pem)  # the key set that named it is gone again
    except OSError:
        log.warning("key step finished, but a key file could not be removed")


def _verify(engine: ApplyEngine, job: Job, expected: list[str]) -> str | None:
    board = engine.board
    board.update(job, "verify", "running")
    host = probe.portal_host(engine.settings.CONFIG_MAIN, engine.settings.AUTH_DOMAIN)
    found = engine.jwks_probe(engine.settings.authelia_base_url, host)
    if isinstance(found, str):
        board.update(job, "verify", "failed", "key set not readable", details=[found])
        return f"Authelia's key set cannot be read: {found}."
    if sorted(found) != sorted(expected):
        board.update(job, "verify", "failed", "unexpected keys",
                     details=[f"expected {', '.join(sorted(expected))}",
                              f"published {', '.join(sorted(found)) or 'none'}"])  # fmt: skip
        return "Authelia does not publish the expected keys."
    board.update(job, "verify", "done", f"{len(found)} key(s) published: {', '.join(found)}")
    return None


def _generate(engine: ApplyEngine, kid: str, algorithm: str) -> Path:
    """Have Authelia create the private key, then move it to its final place (mode 600)."""
    managed = engine.managed
    target = key_path(managed, kid)
    work = managed / ".apply" / f"keygen-{secrets.token_hex(4)}"
    work.mkdir(mode=0o700, parents=True)
    try:
        cli = AutheliaCLI.local(engine.settings.AUTHELIA_BINARY)
        private = cli.generate_key_pair(work, algorithm)
        for folder in (target.parent.parent, target.parent):  # secrets/ and secrets/jwks/
            folder.mkdir(mode=0o700, exist_ok=True)
        os.chmod(private, 0o600)
        os.replace(private, target)
    finally:
        shutil.rmtree(work, ignore_errors=True)  # the public half and anything left over
    return target


def _own_file(engine: ApplyEngine, info: KeyInfo) -> Path | None:
    """The key's file, but only when it is exactly where this tool keeps its keys."""
    try:
        expected = key_path(engine.managed, info.kid)
    except DocumentError:
        return None
    return expected if info.secret_path == str(expected) else None


def _drop(path: Path | None) -> None:
    if path is not None:
        path.unlink(missing_ok=True)
